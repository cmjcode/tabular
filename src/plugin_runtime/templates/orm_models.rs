fn map_diesel_sql_type(raw_type: &str, nullable: bool) -> String {
    let lower = raw_type.to_lowercase();
    let base = if lower.contains("bigint") || lower.contains("int8") {
        "BigInt"
    } else if lower.contains("smallint") || lower.contains("int2") {
        "SmallInt"
    } else if lower.contains("tinyint") || lower.contains("int1") {
        "TinyInt"
    } else if lower.contains("int") || lower.contains("serial") {
        "Integer"
    } else if lower.contains("bool") {
        "Bool"
    } else if lower.contains("double") || lower.contains("float8") {
        "Double"
    } else if lower.contains("float") || lower.contains("real") || lower.contains("float4") {
        "Float"
    } else if lower.contains("timestamp") || lower.contains("datetime") {
        "Timestamp"
    } else if lower.contains("date") {
        "Date"
    } else if lower.contains("time") {
        "Time"
    } else if lower.contains("json") {
        "Jsonb"
    } else if lower.contains("blob") || lower.contains("bytea") || lower.contains("binary") {
        "Binary"
    } else {
        "Text"
    };

    if nullable {
        format!("Nullable<{}>", base)
    } else {
        base.to_string()
    }
}

