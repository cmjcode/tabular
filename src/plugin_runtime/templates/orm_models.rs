use crate::plugin_runtime::host_api::PluginTableSchema;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OrmTarget {
    RustDiesel,
    RustSeaOrm,
    TypeScriptPrisma,
    TypeScriptTypeOrm,
    PythonSqlAlchemy2,
    PythonSqlAlchemy1,
}

impl OrmTarget {
    pub fn display_name(&self) -> &'static str {
        match self {
            OrmTarget::RustDiesel => "Rust (Diesel)",
            OrmTarget::RustSeaOrm => "Rust (SeaORM)",
            OrmTarget::TypeScriptPrisma => "TypeScript (Prisma)",
            OrmTarget::TypeScriptTypeOrm => "TypeScript (TypeORM)",
            OrmTarget::PythonSqlAlchemy2 => "Python (SQLAlchemy 2.0)",
            OrmTarget::PythonSqlAlchemy1 => "Python (SQLAlchemy 1.4)",
        }
    }

    pub fn language(&self) -> &'static str {
        match self {
            OrmTarget::RustDiesel | OrmTarget::RustSeaOrm => "rust",
            OrmTarget::TypeScriptPrisma => "prisma",
            OrmTarget::TypeScriptTypeOrm => "typescript",
            OrmTarget::PythonSqlAlchemy2 | OrmTarget::PythonSqlAlchemy1 => "python",
        }
    }
}

/// Helper to convert snake_case or table name to PascalCase for struct/class names
pub fn to_pascal_case(s: &str) -> String {
    let mut result = String::new();
    let mut capitalize_next = true;
    for c in s.chars() {
        if c == '_' || c == '-' || c == ' ' {
            capitalize_next = true;
        } else if capitalize_next {
            result.push(c.to_ascii_uppercase());
            capitalize_next = false;
        } else {
            result.push(c);
        }
    }
    if result.is_empty() {
        "Entity".to_string()
    } else {
        result
    }
}

/// Helper to convert string to snake_case
pub fn to_snake_case(s: &str) -> String {
    let mut result = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                result.push('_');
            }
            result.push(c.to_ascii_lowercase());
        } else if c == '-' || c == ' ' {
            result.push('_');
        } else {
            result.push(c);
        }
    }
    result
}

/// Generates ORM model code for the specified target
pub fn generate_orm_code(schema: &PluginTableSchema, target: OrmTarget) -> String {
    match target {
        OrmTarget::RustDiesel => generate_diesel(schema),
        OrmTarget::RustSeaOrm => generate_seaorm(schema),
        OrmTarget::TypeScriptPrisma => generate_prisma(schema),
        OrmTarget::TypeScriptTypeOrm => generate_typeorm(schema),
        OrmTarget::PythonSqlAlchemy2 => generate_sqlalchemy2(schema),
        OrmTarget::PythonSqlAlchemy1 => generate_sqlalchemy1(schema),
    }
}

// ---------------------------------------------------------------------------
// 1. Rust Diesel
// ---------------------------------------------------------------------------
fn generate_diesel(schema: &PluginTableSchema) -> String {
    let table_name = &schema.table_name;
    let struct_name = to_pascal_case(table_name);
    let mut out = String::new();

    out.push_str("// Generated by Tabular - Diesel ORM\n");
    out.push_str("use diesel::prelude::*;\n");
    out.push_str("use serde::{Deserialize, Serialize};\n\n");

    // Diesel table! macro
    out.push_str(&format!("diesel::table! {{\n    {} (", table_name));
    let pk_cols: Vec<&str> = schema
        .columns
        .iter()
        .filter(|c| c.is_primary_key)
        .map(|c| c.name.as_str())
        .collect();
    if pk_cols.is_empty() {
        out.push_str("id");
    } else {
        out.push_str(&pk_cols.join(", "));
    }
    out.push_str(") {\n");

    for col in &schema.columns {
        let diesel_type = map_diesel_sql_type(&col.data_type, col.is_nullable);
        out.push_str(&format!("        {} -> {},\n", to_snake_case(&col.name), diesel_type));
    }
    out.push_str("    }\n}\n\n");

    // Rust Model Struct (Queryable)
    out.push_str(&format!(
        "#[derive(Queryable, Selectable, Insertable, Identifiable, Debug, Clone, Serialize, Deserialize)]\n\
         #[diesel(table_name = {})]\n\
         #[diesel(check_for_backend(diesel::pg::Pg))]\n\
         pub struct {} {{\n",
        table_name, struct_name
    ));

    for col in &schema.columns {
        let rust_type = map_rust_type(&col.data_type, col.is_nullable);
        out.push_str(&format!("    pub {}: {},\n", to_snake_case(&col.name), rust_type));
    }
    out.push_str("}\n\n");

    // Insertable NewModel Struct
    out.push_str(&format!(
        "#[derive(Insertable, Debug, Clone, Serialize, Deserialize)]\n\
         #[diesel(table_name = {})]\n\
         pub struct New{} {{\n",
        table_name, struct_name
    ));

    for col in &schema.columns {
        if col.is_auto_increment || (col.is_primary_key && col.default_value.is_some()) {
            continue;
        }
        let rust_type = map_rust_type(&col.data_type, col.is_nullable);
        out.push_str(&format!("    pub {}: {},\n", to_snake_case(&col.name), rust_type));
    }
    out.push_str("}\n");

    out
}

// ---------------------------------------------------------------------------
// 2. Rust SeaORM
// ---------------------------------------------------------------------------
fn generate_seaorm(schema: &PluginTableSchema) -> String {
    let table_name = &schema.table_name;
    let mut out = String::new();

    out.push_str("// Generated by Tabular - SeaORM Entity Model\n");
    out.push_str("use sea_orm::entity::prelude::*;\n");
    out.push_str("use serde::{Deserialize, Serialize};\n\n");

    out.push_str(&format!(
        "#[derive(Clone, Debug, PartialEq, DeriveEntityModel, Eq, Serialize, Deserialize)]\n\
         #[sea_orm(table_name = \"{}\")]\n\
         pub struct Model {{\n",
        table_name
    ));

    for col in &schema.columns {
        let rust_type = map_rust_type(&col.data_type, col.is_nullable);
        let field_name = to_snake_case(&col.name);
        if col.is_primary_key {
            if col.is_auto_increment {
                out.push_str("    #[sea_orm(primary_key)]\n");
            } else {
                out.push_str("    #[sea_orm(primary_key, auto_increment = false)]\n");
            }
        }
        if col.name != field_name {
            out.push_str(&format!("    #[sea_orm(column_name = \"{}\")]\n", col.name));
        }
        out.push_str(&format!("    pub {}: {},\n", field_name, rust_type));
    }
    out.push_str("}\n\n");

    out.push_str(
        "#[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]\n\
         pub enum Relation {}\n\n\
         impl ActiveModelBehavior for ActiveModel {}\n",
    );

    out
}

// ---------------------------------------------------------------------------
// 3. TypeScript Prisma
// ---------------------------------------------------------------------------
fn generate_prisma(schema: &PluginTableSchema) -> String {
    let model_name = to_pascal_case(&schema.table_name);
    let mut out = String::new();

    out.push_str("// Generated by Tabular - Prisma Schema Model\n");
    out.push_str(&format!("model {} {{\n", model_name));

    for col in &schema.columns {
        let prisma_type = map_prisma_type(&col.data_type);
        let nullable_suffix = if col.is_nullable { "?" } else { "" };
        let mut attributes = Vec::new();

        if col.is_primary_key {
            attributes.push("@id".to_string());
            if col.is_auto_increment {
                attributes.push("@default(autoincrement())".to_string());
            }
        }
        if let Some(def) = &col.default_value {
            if !col.is_auto_increment && !def.is_empty() {
                if def.to_lowercase().contains("now") || def.to_lowercase().contains("current_timestamp") {
                    attributes.push("@default(now())".to_string());
                } else if let Ok(n) = def.parse::<i64>() {
                    attributes.push(format!("@default({})", n));
                } else if def.eq_ignore_ascii_case("true") || def.eq_ignore_ascii_case("false") {
                    attributes.push(format!("@default({})", def.to_lowercase()));
                }
            }
        }

        let attr_str = if attributes.is_empty() {
            String::new()
        } else {
            format!(" {}", attributes.join(" "))
        };

        out.push_str(&format!(
            "  {:16} {}{}{}\n",
            col.name, prisma_type, nullable_suffix, attr_str
        ));
    }

    if schema.table_name != model_name {
        out.push_str(&format!("\n  @@map(\"{}\")\n", schema.table_name));
    }
    out.push_str("}\n");

    out
}

// ---------------------------------------------------------------------------
// 4. TypeScript TypeORM
// ---------------------------------------------------------------------------
fn generate_typeorm(schema: &PluginTableSchema) -> String {
    let class_name = to_pascal_case(&schema.table_name);
    let mut out = String::new();

    out.push_str("// Generated by Tabular - TypeORM Entity\n");
    out.push_str("import { Entity, PrimaryGeneratedColumn, PrimaryColumn, Column, CreateDateColumn, UpdateDateColumn } from \"typeorm\";\n\n");

    out.push_str(&format!("@Entity(\"{}\")\nexport class {} {{\n", schema.table_name, class_name));

    for col in &schema.columns {
        let ts_type = map_typescript_type(&col.data_type);
        let field_name = to_snake_case(&col.name);

        if col.is_primary_key {
            if col.is_auto_increment {
                out.push_str("  @PrimaryGeneratedColumn()\n");
            } else {
                out.push_str("  @PrimaryColumn()\n");
            }
        } else if col.is_nullable {
            out.push_str(&format!("  @Column({{ nullable: true, name: \"{}\" }})\n", col.name));
        } else {
            out.push_str(&format!("  @Column({{ name: \"{}\" }})\n", col.name));
        }

        let optional = if col.is_nullable { "?" } else { "" };
        out.push_str(&format!("  {}{}: {};\n\n", field_name, optional, ts_type));
    }

    out.push_str("}\n");
    out
}

// ---------------------------------------------------------------------------
// 5. Python SQLAlchemy 2.0
// ---------------------------------------------------------------------------
fn generate_sqlalchemy2(schema: &PluginTableSchema) -> String {
    let class_name = to_pascal_case(&schema.table_name);
    let mut out = String::new();

    out.push_str("# Generated by Tabular - SQLAlchemy 2.0 Model\n");
    out.push_str("from typing import Optional\n");
    out.push_str("from datetime import datetime, date, time\n");
    out.push_str("from sqlalchemy import String, Integer, BigInteger, Float, Boolean, DateTime, Date, Time, Text\n");
    out.push_str("from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column\n\n");
    out.push_str("class Base(DeclarativeBase):\n    pass\n\n");

    out.push_str(&format!("class {}(Base):\n", class_name));
    out.push_str(&format!("    __tablename__ = \"{}\"\n\n", schema.table_name));

    for col in &schema.columns {
        let py_type = map_python_type(&col.data_type);
        let field_name = to_snake_case(&col.name);
        let mut col_args = Vec::new();

        if col.is_primary_key {
            col_args.push("primary_key=True".to_string());
        }
        if col.is_auto_increment {
            col_args.push("autoincrement=True".to_string());
        }
        if col.name != field_name {
            col_args.push(format!("name=\"{}\"", col.name));
        }

        let arg_str = if col_args.is_empty() {
            String::new()
        } else {
            col_args.join(", ")
        };

        if col.is_nullable {
            out.push_str(&format!(
                "    {}: Mapped[Optional[{}]] = mapped_column({})\n",
                field_name, py_type, arg_str
            ));
        } else {
            out.push_str(&format!(
                "    {}: Mapped[{}] = mapped_column({})\n",
                field_name, py_type, arg_str
            ));
        }
    }

    out
}

// ---------------------------------------------------------------------------
// 6. Python SQLAlchemy 1.4 (Classic)
// ---------------------------------------------------------------------------
fn generate_sqlalchemy1(schema: &PluginTableSchema) -> String {
    let class_name = to_pascal_case(&schema.table_name);
    let mut out = String::new();

    out.push_str("# Generated by Tabular - SQLAlchemy 1.4 (Classic)\n");
    out.push_str("from sqlalchemy import Column, Integer, BigInteger, String, Float, Boolean, DateTime, Date, Time, Text\n");
    out.push_str("from sqlalchemy.ext.declarative import declarative_base\n\n");
    out.push_str("Base = declarative_base()\n\n");

    out.push_str(&format!("class {}(Base):\n", class_name));
    out.push_str(&format!("    __tablename__ = \"{}\"\n\n", schema.table_name));

    for col in &schema.columns {
        let sqla_type = map_sqla_column_type(&col.data_type);
        let field_name = to_snake_case(&col.name);
        let mut col_args = vec![sqla_type];

        if col.is_primary_key {
            col_args.push("primary_key=True");
        }
        if !col.is_nullable {
            col_args.push("nullable=False");
        }

        out.push_str(&format!(
            "    {} = Column({})\n",
            field_name,
            col_args.join(", ")
        ));
    }

    out
}

